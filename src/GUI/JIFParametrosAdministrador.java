    /**
     * Maneja la acción del botón "Guardar configuración de minijuegos".
     *
     * Este método realiza lo siguiente:
     *  Validación: Verifica que el usuario haya seleccionado una modalidad de juego para el minijuego Combat (Teclado compartido o Por turnos). 
     *     Si ninguna opción está seleccionada, muestra un cuadro de advertencia y no continúa.
     * 
     *  Cálculo del nivel: Obtiene el índice seleccionado en el combo box de dificultad y le suma 1 para obtener el número de nivel.
     * 
     *  Creación de objetos de configuración: Instancia un {@link ConfiguracionDonutRace}, un {@link ConfiguracionGroggyRing}
     *      y un {@link ConfiguracionCombat} y llama a  {@link ConfiguracionDonutRace#seleccionNivel(int) seleccionNivel(opcion)} 
     *      sobre cada uno para asignar el nivel correspondiente.
     *  
     *  Guardado en la ventana principal: Si la referencia a {@code ventanaPrincipal} no es {@code null}, invoca 
     *      {@link JFVentanaPrincipal#guardarConfiguracion(ConfiguracionDonutRace, ConfiguracionGroggyRing, ConfiguracionCombat)
     *       ventanaPrincipal.guardarConfiguracion(donut, groggy, combat)} para almacenar la configuración en los atributos 
     *       {@code configuracionDonut}, {@code configuracionGroggy} y {@code configuracionCombat} de la ventana principal.
     *  
     *  Liberación de recursos:Cierra y libera este panel interno llamando a {@link #dispose()}.
     *
     *  Efecto secundario: Los objetos de configuración creados ({@code donut}, {@code groggy} y {@code combat}) se almacenan en 
     *      los atributos correspondientes de la ventana principal y se muestra un mensaje de confirmación al usuario.
     *
     * @param evt el evento de acción generado al hacer clic en el botón "Guardar configuración de minijuegos"
     */
    
    private void jbtnGuardarConfiguracionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnGuardarConfiguracionActionPerformed

        if (!btnTecladoCompartido.isSelected() && !btnTurnos.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(rootPane, "Faltan parámetros por configurar, debe seleccionar una modalidad de juego para el minijuego Combat");
        } else {
            int opcion = jcbDificultad.getSelectedIndex() + 1;
            ConfiguracionDonutRace donut = new ConfiguracionDonutRace();
            donut.seleccionNivel(opcion);
            this.configuraciones.add( donut );
            
            ConfiguracionGroggyRing groggy = new ConfiguracionGroggyRing();
            groggy.seleccionNivel(opcion);
            this.configuraciones.add(groggy);
        
            ConfiguracionCombat combat = new ConfiguracionCombat();
            combat.seleccionNivel(opcion);
            this.configuraciones.add(combat);
        
        if (this.ventanaPrincipal != null) {
            this.ventanaPrincipal.guardarConfiguracion( this.configuraciones);
        }
        
        this.dispose();
        
        }
    }//GEN-LAST:event_jbtnGuardarConfiguracionActionPerformed

